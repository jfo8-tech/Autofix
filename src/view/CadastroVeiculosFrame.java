    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
        String modelo = jTextField1.getText().trim();
String placa = jTextField2.getText().trim();
String ano = jTextField3.getText().trim();
String cor = jTextField5.getText().trim();
String quilometragem = jTextField6.getText().trim();
String valor = jTextField4.getText().trim();

// Verificar os campos de texto
if (modelo.isEmpty() || placa.isEmpty() || ano.isEmpty()
        || cor.isEmpty() || quilometragem.isEmpty() || valor.isEmpty()) {

    javax.swing.JOptionPane.showMessageDialog(this,
            "Preencha todos os campos!");
    return;
}

// Verificar as opções selecionadas
if (jComboBox3.getSelectedIndex() == 0
        || jComboBox1.getSelectedIndex() == 0
        || jComboBox6.getSelectedIndex() == 0) {

    javax.swing.JOptionPane.showMessageDialog(this,
            "Selecione a marca, o combustível e a categoria!");
    return;
}

// Verificar ano, quilometragem e valor
try {
    int anoVeiculo = Integer.parseInt(ano);
    int km = Integer.parseInt(quilometragem);
    double preco = Double.parseDouble(valor.replace(",", "."));

    if (anoVeiculo < 1886 || anoVeiculo > java.time.Year.now().getValue()) {
        javax.swing.JOptionPane.showMessageDialog(this,
                "Informe um ano válido!");
        return;
    }

    if (km < 0 || preco <= 0) {
        javax.swing.JOptionPane.showMessageDialog(this,
                "Quilometragem ou valor inválido!");
        return;
    }

} catch (NumberFormatException e) {
    javax.swing.JOptionPane.showMessageDialog(this,
            "Ano, quilometragem e valor devem conter números válidos!");
    return;
}

javax.swing.JOptionPane.showMessageDialog(this,
        "Todos os dados foram preenchidos corretamente!");
    }//GEN-LAST:event_jButton3ActionPerformed

